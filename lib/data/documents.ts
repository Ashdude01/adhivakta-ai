import 'server-only';
import { createSupabaseAdmin } from '@/lib/supabase/server';
import type { DbMatterDocument } from '@/lib/supabase/types';
import { getMatter } from '@/lib/data/matters';
import { isUuid } from '@/lib/validation/uuid';

const BUCKET = process.env.SUPABASE_BUCKET || 'adhikarik_bucket';

/** Signed links are handed to the browser; keep the window short. */
const SIGNED_URL_TTL_SECONDS = 300;

export const MAX_UPLOAD_BYTES = 25 * 1024 * 1024;

/**
 * What a court file actually holds. Rejecting everything else keeps executables
 * and HTML (which would run from a signed URL) out of the bucket.
 */
export const ALLOWED_MIME = new Set([
  'application/pdf',
  'image/jpeg', 'image/png', 'image/webp', 'image/heic',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/vnd.ms-excel',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  'text/plain',
]);

export const DOCUMENT_KINDS = [
  'evidence', 'vakalatnama', 'court_order', 'correspondence',
  'id_proof', 'agreement', 'invoice', 'signed', 'other',
] as const;
export type DocumentKind = (typeof DOCUMENT_KINDS)[number];

export async function listDocuments(userId: string, matterId: string): Promise<DbMatterDocument[]> {
  const sb = createSupabaseAdmin();
  const { data, error } = await sb
    .from('matter_documents')
    .select('*')
    .eq('user_id', userId)
    .eq('matter_id', matterId)
    .order('uploaded_at', { ascending: false });
  if (error) throw error;
  return (data as DbMatterDocument[]) ?? [];
}

export async function uploadDocument(
  userId: string,
  matterId: string,
  input: { file: File; kind: DocumentKind; description?: string },
): Promise<DbMatterDocument> {
  const matter = await getMatter(userId, matterId);
  if (!matter) throw new Error('Matter not found');

  const { file, kind, description } = input;
  if (file.size > MAX_UPLOAD_BYTES) throw new Error('File is larger than 25 MB');
  if (!ALLOWED_MIME.has(file.type)) throw new Error(`Files of type "${file.type || 'unknown'}" are not accepted`);

  // Scoped by user then matter so one advocate's key can never collide with
  // another's, and a random suffix so re-uploading the same name never clobbers.
  const safeName = sanitiseFileName(file.name);
  const path = `matters/${userId}/${matterId}/${crypto.randomUUID()}-${safeName}`;

  const sb = createSupabaseAdmin();
  const { error: uploadError } = await sb.storage
    .from(BUCKET)
    .upload(path, file, { contentType: file.type, upsert: false });
  if (uploadError) throw uploadError;

  const { data, error } = await sb
    .from('matter_documents')
    .insert({
      user_id: userId,
      matter_id: matterId,
      storage_path: path,
      file_name: safeName,
      mime_type: file.type,
      size_bytes: file.size,
      kind,
      description: description || null,
    })
    .select('*')
    .single();

  if (error) {
    // Do not leave an unreferenced object behind in the bucket.
    await sb.storage.from(BUCKET).remove([path]).catch(() => undefined);
    throw error;
  }
  return data as DbMatterDocument;
}

/**
 * Stores server-generated bytes (a signed PDF) as a matter document. Same
 * private-bucket path scheme as an upload, so it is served the same signed-URL
 * way and cleaned up when the matter is deleted.
 */
export async function storeBytesAsDocument(
  userId: string,
  matterId: string,
  input: { fileName: string; bytes: Uint8Array; mimeType: string; kind: DocumentKind; description?: string },
): Promise<DbMatterDocument> {
  const matter = await getMatter(userId, matterId);
  if (!matter) throw new Error('Matter not found');

  const safeName = sanitiseFileName(input.fileName);
  const path = `matters/${userId}/${matterId}/${crypto.randomUUID()}-${safeName}`;

  const sb = createSupabaseAdmin();
  const { error: uploadError } = await sb.storage
    .from(BUCKET)
    .upload(path, input.bytes, { contentType: input.mimeType, upsert: false });
  if (uploadError) throw uploadError;

  const { data, error } = await sb
    .from('matter_documents')
    .insert({
      user_id: userId, matter_id: matterId, storage_path: path, file_name: safeName,
      mime_type: input.mimeType, size_bytes: input.bytes.byteLength,
      kind: input.kind, description: input.description ?? null,
    })
    .select('*').single();
  if (error) {
    await sb.storage.from(BUCKET).remove([path]).catch(() => undefined);
    throw error;
  }
  return data as DbMatterDocument;
}

export async function getDocument(userId: string, documentId: string): Promise<DbMatterDocument | null> {
  if (!isUuid(documentId)) return null;
  const sb = createSupabaseAdmin();
  const { data, error } = await sb
    .from('matter_documents').select('*')
    .eq('id', documentId).eq('user_id', userId)
    .maybeSingle();
  if (error) throw error;
  return (data as DbMatterDocument) ?? null;
}

/** A short-lived link to a private object. Ownership is checked by the caller. */
export async function signedUrlFor(document: DbMatterDocument): Promise<string> {
  const sb = createSupabaseAdmin();
  const { data, error } = await sb.storage
    .from(BUCKET)
    .createSignedUrl(document.storage_path, SIGNED_URL_TTL_SECONDS);
  if (error) throw error;
  return data.signedUrl;
}

export async function deleteDocument(userId: string, documentId: string): Promise<void> {
  const document = await getDocument(userId, documentId);
  if (!document) throw new Error('Document not found');

  const sb = createSupabaseAdmin();
  // Row first: an orphaned object is invisible clutter, but an orphaned row is
  // a broken download the advocate keeps clicking.
  const { error } = await sb.from('matter_documents').delete().eq('id', documentId).eq('user_id', userId);
  if (error) throw error;
  await sb.storage.from(BUCKET).remove([document.storage_path]);
}

function sanitiseFileName(name: string): string {
  return name
    .replace(/[/\\]/g, '-')
    .replace(/[^\w\d.\- ]+/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 120) || 'file';
}
